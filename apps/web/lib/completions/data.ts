/** A snippet named like a keyword (`for`, `while`) replaces it, so the list never shows the same word twice. */
const merge = (...lists: Entry[][]): Entry[] => {
  const all = lists.flat();
  const snippets = new Set(all.filter((e) => e.kind === 'snippet').map((e) => e.label));
  const seen = new Set<string>();
  return all.filter((e) => {
    if (e.kind === 'keyword' && snippets.has(e.label)) return false;
    if (seen.has(e.label)) return false;
    seen.add(e.label);
    return true;
  });
};

