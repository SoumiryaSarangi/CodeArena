/**
 * ED-01 (FR-EDIT-01): what the editors suggest beyond the words already typed. Monaco has no language service for
 * C, C++, Java or Python, so without this only `int` or `cout` that are already in the file ever appear. The lists are
 * what contestants actually type, not a whole standard library: a long list is noise.
 */
export type EntryKind = 'keyword' | 'function' | 'class' | 'snippet';

export interface Entry {
  label: string;
  kind: EntryKind;
  /** Inserted text. Snippets use Monaco's syntax (`${1:n}` tab stops, `$0` final cursor); omitted: the label. */
  insert?: string;
  detail?: string;
}

const kw = (...labels: string[]): Entry[] => labels.map((label) => ({ label, kind: 'keyword' }));
const fn = (...labels: string[]): Entry[] => labels.map((label) => ({ label, kind: 'function' }));
const cls = (...labels: string[]): Entry[] => labels.map((label) => ({ label, kind: 'class' }));
const sn = (label: string, detail: string, insert: string): Entry => ({
  label,
  kind: 'snippet',
  detail,
  insert,
});

